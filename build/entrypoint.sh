#!/bin/bash
# ==================================================================================
# entrypoint.sh — Samba AD container entrypoint
# ==================================================================================
# This script:
#   1. Configures the system environment (hostname, /etc/hosts, resolv.conf)
#   2. Detects whether Samba is already provisioned or not
#   3. If provisioned: starts Samba
#   4. If not provisioned: displays instructions and keeps the container running
# ==================================================================================

set -euo pipefail

# ─── Colors ─────────────────────────────────────────────────────────
WHITE='\033[1;37m'
GREEN='\033[0;32m'
YELLOW='\033[1;33m'
RED='\033[0;31m'
BLUE='\033[0;34m'
CYAN='\033[0;36m'
NC='\033[0m'

# ─── Log functions ──────────────────────────────────────────────────
log_info()    { echo -e "${GREEN}[INFO]${NC}  $*"; }
log_warn()    { echo -e "${YELLOW}[WARN]${NC}  $*"; }
log_error()   { echo -e "${RED}[ERROR]${NC} $*"; }
log_section() { echo -e "\n${CYAN}══════════════════════════════════════════${NC}"; echo -e "${CYAN}  $*${NC}"; echo -e "${CYAN}══════════════════════════════════════════${NC}"; }

# ─── Variables ──────────────────────────────────────────────────────
DC_HOSTNAME=$(hostname)
DOMAIN_REALM="${DOMAIN_REALM:-JJLABS.LAN}"
DOMAIN_NAME="${DOMAIN_NAME:-JJLABS}"
DNS_FORWARDER="${DNS_FORWARDER:-8.8.8.8}"
TIMEZONE="${TIMEZONE:-Europe/Paris}"

# Required
: "${DOCKER_HOST_IP:?DOCKER_HOST_IP is required (ex: 192.168.0.1)}"
: "${DOMAIN_NETWORK:?DOMAIN_NETWORK is required (ex: 192.168.0.0/24)}"

# ─── Convert domain infos to uppercase ──────────────────────────────
DOMAIN_REALM_UPPER=$(echo "$DOMAIN_REALM" | tr '[:lower:]' '[:upper:]')
DOMAIN_REALM_LOWER=$(echo "$DOMAIN_REALM" | tr '[:upper:]' '[:lower:]')
DOMAIN_NAME_UPPER=$(echo "$DOMAIN_NAME" | tr '[:lower:]' '[:upper:]')



# ─── Check whether Samba is already provisioned ─────────────────────
is_provisioned() {
    [ -f "/etc/samba/smb.conf" ] && [ -f "/var/lib/samba/private/sam.ldb" ]
}


# ─── Configuring /etc/hosts ─────────────────────────────────────────
configure_hosts() {
    # Cleaning existing entries
    sed -i "/${DC_HOSTNAME}/d" /etc/hosts 2>/dev/null || true

    # Add new entry
    echo "${DOCKER_HOST_IP} ${DC_HOSTNAME}.${DOMAIN_REALM_LOWER} ${DC_HOSTNAME}" >> /etc/hosts
}


# ─── Configuring /etc/resolv.conf ──────────────
configure_resolv() {
    cat > /etc/resolv.conf <<EOF
# Generated by entrypoint.sh - Samba AD DC
nameserver ${DOCKER_HOST_IP}
search ${DOMAIN_REALM_LOWER}
domain ${DOMAIN_REALM_LOWER}
EOF
}


# ─── Configuring /etc/resolv.conf ──────────────
create_krb5_link() {
    ln -sf /var/lib/samba/private/krb5.conf /etc/krb5.conf
}


# ─── Configuring /etc/chrony/chrony.conf ──────────────
configure_chrony() {
    # ntpsigndsocket
    local ntp_socket_dir="/var/lib/samba/ntp_signd"
    mkdir -p "${ntp_socket_dir}"
    chown root:_chrony ${ntp_socket_dir}
    chmod 750 ${ntp_socket_dir}

    # chrony conf
    local conf_dir="/etc/chrony/conf.d"
    local conf_file="${conf_dir}/01-samba-ad-dc.conf"

    mkdir -p "${conf_dir}"
    touch "${conf_file}"

    grep -qxF "allow ${DOMAIN_NETWORK}" "${conf_file}" \
        || echo "allow ${DOMAIN_NETWORK}" >> "${conf_file}"

    grep -qxF "ntpsigndsocket /var/lib/samba/ntp_signd" "${conf_file}" \
        || echo "ntpsigndsocket /var/lib/samba/ntp_signd" >> "${conf_file}"
}


# ─── Affichage des commandes disponibles ────────────────────────────
show_help() {
    log_section "🚀 Samba AD DC - Ready to configure"
    echo ""
    echo -e "${YELLOW}Environment variables loaded:${NC}"
    echo -e "  DC_HOSTNAME    = ${CYAN}${DC_HOSTNAME}${NC}"
    echo -e "  DOMAIN_REALM   = ${CYAN}${DOMAIN_REALM_UPPER}${NC}"
    echo -e "  DOMAIN_NAME    = ${CYAN}${DOMAIN_NAME_UPPER}${NC}"
    echo -e "  DNS_FORWARDER  = ${CYAN}${DNS_FORWARDER}${NC}"
    echo -e "  DOCKER_HOST_IP = ${CYAN}${DOCKER_HOST_IP}${NC}"
    echo -e "  DOMAIN_NETWORK = ${CYAN}${DOMAIN_NETWORK}${NC}"
    echo ""

    log_section "📋 OPTION 1 — Provisioning a new domain"
    echo ""
    echo -e "${YELLOW}Run the following command from your host:${NC}"
    echo ""
    echo -e "${GREEN}  sudo docker compose exec -it dc samba-provision${NC}"
    echo ""
    echo -e "  The previous command is an alias for:"
    echo -e "  ${BLUE}samba-tool domain provision \\\\${NC}"
    echo -e "  ${BLUE}    --host-ip=$DOCKER_HOST_IP \\\\${NC}"
    echo -e "  ${BLUE}    --server-role=dc \\\\${NC}"
    echo -e "  ${BLUE}    --use-rfc2307 \\\\${NC}"
    echo -e "  ${BLUE}    --dns-backend=SAMBA_INTERNAL \\\\${NC}"
    echo -e "  ${BLUE}    --realm=${DOMAIN_REALM_UPPER} \\\\${NC}"
    echo -e "  ${BLUE}    --domain=${DOMAIN_NAME_UPPER} \\\\${NC}"
    echo -e "  ${BLUE}    --option=\"dns forwarder=${DNS_FORWARDER}\"${NC}"
    echo -e "  ${BLUE}    --option=\"interfaces=lo ${DOCKER_HOST_IP}\" \\\\${NC}"
    echo -e "  ${BLUE}    --option=\"bind interfaces only=yes\" \\\\${NC}"
    echo ""
    echo -e "  Add ${YELLOW}--adminpass='Ch@ngeThisP@\$Sw0rd!'${NC} to set the administrator password"
    echo ""

    log_section "📋 OPTION 2 — Joining an existing domain"
    echo ""
    echo -e "${YELLOW}Run the following command from your host:${NC}"
    echo ""
    echo -e "${GREEN}  sudo docker compose exec -it dc samba-join${NC}"
    echo ""
    echo -e "  The previous command is an alias for:"
    echo -e "  ${BLUE}samba-tool domain join ${DOMAIN_REALM_LOWER} DC \\\\${NC}"
    echo -e "  ${BLUE}    --dns-backend=SAMBA_INTERNAL \\\\${NC}"
    echo -e "  ${BLUE}    --option='idmap_ldb:use rfc2307=yes' \\\\${NC}"
    echo -e "  ${BLUE}    --option=\"dns forwarder=${DNS_FORWARDER}\" \\\\${NC}"
    echo -e "  ${BLUE}    --option=\"interfaces=lo ${DOCKER_HOST_IP}\" \\\\${NC}"
    echo -e "  ${BLUE}    --option=\"bind interfaces only=yes\" \\\\${NC}"
    echo ""

    log_section "📋 OPTION 3 — Starting interactive shell"
    echo ""
    echo -e "${YELLOW}Run the following command from your host:${NC}"
    echo ""
    echo -e "${GREEN}  sudo docker compose exec -it dc bash${NC}"
    echo ""
    echo ""
}


# ─── Signal handling ────────────────────────────────────────────────
_shutdown() {
    log_info "Stopping Samba AD..."

    service chrony stop 2>/dev/null || true

    log_info "Samba stopped."
    exit 0
}
trap _shutdown SIGTERM SIGINT SIGQUIT


# ════════════════════════════════════════════════════════════════════
# MAIN
# ════════════════════════════════════════════════════════════════════
log_section "🐧 Samba 4 AD DC — Starting container"


# ─── Verify Samba installation ──────────────────────────────────────
echo ""
if ! command -v samba >/dev/null 2>&1; then
    log_error "Samba is not installed or not found in PATH."
    exit 1
fi
log_info "Samba: $(samba --version)"
log_info "Samba is installed and ready"


# ─── Configurations ─────────────────────────────────────────────────
log_info "Configuring /etc/hosts"
configure_hosts

log_info "Configuring /etc/resolv.conf"
configure_resolv

log_info "Creating symlink /etc/krb5.conf => /var/lib/samba/private/krb5.conf"
create_krb5_link

log_info "Configuring /etc/chrony/chrony.conf"
configure_chrony

log_info "Starting chrony"
service chrony start > /dev/null


# ─── Checking domain provisioning state - Keep container alive ──────
if ! is_provisioned; then
    log_warn "No Samba configuration or database found."
    echo ""
    show_help
    
    log_info "Samba not provisioned — waiting..."
    while ! is_provisioned; do
        sleep 5
    done
fi


# After detection, waits an additional 15 seconds for provisioning to stabilize
# Starting Samba too early may cause inconsistent state or failed initialization
log_info "Provisioning detected — starting Samba in 15 seconds..."
sleep 15
log_info "🚀 Starting Samba AD DC"
exec samba --foreground
